#!/usr/bin/env python3
# gen-daostubs.py - writes daostubs.h from a dbdaoint.h: for each DAO
# interface, a class that implements IUnknown and every method, the
# interface's own methods failing with E_NOTIMPL. The stand-in engine in
# daomock.h derives from these and overrides what it does.
#
#   python3 tests/gen-daostubs.py SYSROOT/include/dbdaoint.h > tests/daostubs.h
import re
import sys

src = open(sys.argv[1]).read()
ifaces = {}
order = []
for m in re.finditer(r'DECLARE_INTERFACE_\((\w+),(\w+)\)\s*\{(.*?)\n\};', src, re.S):
    name, base, body = m.groups()
    body = re.sub(r'#ifndef __cplusplus.*?#endif', '', body, flags=re.S)
    meths = []
    for mm in re.finditer(r'STDMETHOD(?:_\(\s*(\w+)\s*,\s*(\w+)\s*\)|\((\w+)\))\s*\((.*?)\)\s*PURE;',
                          body, re.S):
        if mm.group(1):
            ret, mname = mm.group(1), mm.group(2)
        else:
            ret, mname = 'HRESULT', mm.group(3)
        args = ' '.join(mm.group(4).split())
        args = args.replace('THIS_', '').replace('THIS', '').strip()
        args = re.sub(r'\binterface\b', 'struct', args)
        meths.append((ret, mname, args))
    ifaces[name] = (base, meths)
    order.append(name)


def flat(n):
    if n not in ifaces:
        return []
    b, ms = ifaces[n]
    return flat(b) + ms


out = ['// daostubs.h - generated by gen-daostubs.py from dbdaoint.h; do not edit.',
       '#pragma once', '#include <dbdaoint.h>', '']
for n in order:
    out.append('struct Stub%s : public %s {' % (n, n))
    out.append('  LONG m_cRef = 1;')
    out.append('  virtual ~Stub%s() {}' % n)
    out.append('  virtual bool IsIID(REFIID) { return false; }')
    out.append('  STDMETHOD(QueryInterface)(REFIID riid, void** ppv) {')
    out.append('    if (IsEqualIID(riid, IID_IUnknown) || IsEqualIID(riid, IID_IDispatch) || IsIID(riid)) {')
    out.append('      *ppv = this;')
    out.append('      AddRef();')
    out.append('      return S_OK;')
    out.append('    }')
    out.append('    *ppv = NULL;')
    out.append('    return E_NOINTERFACE;')
    out.append('  }')
    out.append('  STDMETHOD_(ULONG, AddRef)() { return (ULONG)++m_cRef; }')
    out.append('  STDMETHOD_(ULONG, Release)() {')
    out.append('    LONG n = --m_cRef;')
    out.append('    if (n == 0) delete this;')
    out.append('    return (ULONG)n;')
    out.append('  }')
    out.append('  STDMETHOD(GetTypeInfoCount)(UINT*) { return E_NOTIMPL; }')
    out.append('  STDMETHOD(GetTypeInfo)(UINT, LCID, ITypeInfo**) { return E_NOTIMPL; }')
    out.append('  STDMETHOD(GetIDsOfNames)(REFIID, LPOLESTR*, UINT, LCID, DISPID*) { return E_NOTIMPL; }')
    out.append('  STDMETHOD(Invoke)(DISPID, REFIID, LCID, WORD, DISPPARAMS*, VARIANT*, EXCEPINFO*, UINT*) {')
    out.append('    return E_NOTIMPL;')
    out.append('  }')
    for ret, mn, args in flat(n):
        if ret == 'HRESULT':
            out.append('  STDMETHOD(%s)(%s) { return E_NOTIMPL; }' % (mn, args))
        else:
            out.append('  STDMETHOD_(%s, %s)(%s) { return 0; }' % (ret, mn, args))
    out.append('};')
    out.append('')
sys.stdout.write('\n'.join(out))
