#!/usr/bin/env python3
"""gen-html-stubs.py - writes htmlstubs.h for htmltest: for each of the
HTML interfaces the test fakes, a class whose methods (its own and its
bases', down to IDispatch) all return E_NOTIMPL. The test's fakes derive
from these and answer only what CDHtmlDialog asks.

Usage: gen-html-stubs.py <mshtml.h> > tests/htmlstubs.h
"""
import re
import sys

INTERFACES = ["IHTMLDocument2", "IHTMLElement", "IHTMLElementCollection", "IHTMLEventObj"]

text = open(sys.argv[1]).read()


def interface(name):
    m = re.search(r"MIDL_INTERFACE\(\"[^\"]+\"\)\s*\n" + name + r" : public (\w+)\s*\{(.*?)\n\};",
                  text, re.S)
    if not m:
        sys.exit("no interface " + name)
    base, body = m.group(1), m.group(2)
    methods = []
    for decl in re.findall(r"virtual (HRESULT STDMETHODCALLTYPE .*?) = 0;", body, re.S):
        decl = " ".join(decl.split())
        # Default arguments are the interface's; the stubs do without.
        decl = re.sub(r"\s*=\s*[^,)]+", "", decl)
        methods.append(decl)
    return base, methods


out = ["// htmlstubs.h - generated by gen-html-stubs.py from mshtml.h; do not edit.",
       "// Classes whose HTML interface methods all return E_NOTIMPL, for the",
       "// test's fake documents and elements to derive from.",
       "#pragma once", "#include <mshtml.h>", ""]
for name in INTERFACES:
    chain = []
    n = name
    while n not in ("IDispatch", "IUnknown"):
        base, methods = interface(n)
        chain = methods + chain
        n = base
    out.append("class CStub%s : public %s {" % (name[1:], name))
    out.append("public:")
    for decl in chain:
        out.append("  virtual %s { return E_NOTIMPL; }" % decl)
    out.append("};")
    out.append("")
print("\n".join(out))
