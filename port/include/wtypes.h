typedef union tagCY {
  struct {
#if defined(__BYTE_ORDER__) && __BYTE_ORDER__ == __ORDER_BIG_ENDIAN__
    int Hi;
    unsigned int Lo;
#else
    unsigned int Lo;
    int Hi;
#endif
  };
  LONGLONG int64;
} CY, CURRENCY, *LPCY;

typedef struct tagDEC {
  USHORT wReserved;
  union {
    struct {
      BYTE scale;
      BYTE sign;
    };
    USHORT signscale;
  };
  ULONG Hi32;
  union {
    struct {
      ULONG Lo32;
      ULONG Mid32;
    };
    ULONGLONG Lo64;
  };
} DECIMAL, *LPDECIMAL;
#define DECIMAL_NEG ((BYTE)0x80)
#define DECIMAL_SETZERO(dec) \
  { (dec).Lo64 = 0; (dec).Hi32 = 0; (dec).signscale = 0; }

