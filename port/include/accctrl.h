#ifndef _WINPORT_ACCCTRL_H
#define _WINPORT_ACCCTRL_H

#include <windows.h>

typedef enum _SE_OBJECT_TYPE {
  SE_UNKNOWN_OBJECT_TYPE = 0,
  SE_FILE_OBJECT,
  SE_SERVICE,
  SE_PRINTER,
  SE_REGISTRY_KEY,
  SE_LMSHARE,
  SE_KERNEL_OBJECT,
  SE_WINDOW_OBJECT,
  SE_DS_OBJECT,
  SE_DS_OBJECT_ALL,
  SE_PROVIDER_DEFINED_OBJECT,
  SE_WMIGUID_OBJECT,
  SE_REGISTRY_WOW64_32KEY
} SE_OBJECT_TYPE;

typedef enum _TRUSTEE_TYPE {
  TRUSTEE_IS_UNKNOWN,
  TRUSTEE_IS_USER,
  TRUSTEE_IS_GROUP,
  TRUSTEE_IS_DOMAIN,
  TRUSTEE_IS_ALIAS,
  TRUSTEE_IS_WELL_KNOWN_GROUP,
  TRUSTEE_IS_DELETED,
  TRUSTEE_IS_INVALID,
  TRUSTEE_IS_COMPUTER
} TRUSTEE_TYPE;
typedef enum _TRUSTEE_FORM {
  TRUSTEE_IS_SID,
  TRUSTEE_IS_NAME,
  TRUSTEE_BAD_FORM,
  TRUSTEE_IS_OBJECTS_AND_SID,
  TRUSTEE_IS_OBJECTS_AND_NAME
} TRUSTEE_FORM;
typedef enum _MULTIPLE_TRUSTEE_OPERATION { NO_MULTIPLE_TRUSTEE, TRUSTEE_IS_IMPERSONATE } MULTIPLE_TRUSTEE_OPERATION;
typedef struct _TRUSTEE_A {
  struct _TRUSTEE_A* pMultipleTrustee;
  MULTIPLE_TRUSTEE_OPERATION MultipleTrusteeOperation;
  TRUSTEE_FORM TrusteeForm;
  TRUSTEE_TYPE TrusteeType;
  LPSTR ptstrName;
} TRUSTEE_A, *PTRUSTEE_A;
typedef struct _TRUSTEE_W {
  struct _TRUSTEE_W* pMultipleTrustee;
  MULTIPLE_TRUSTEE_OPERATION MultipleTrusteeOperation;
  TRUSTEE_FORM TrusteeForm;
  TRUSTEE_TYPE TrusteeType;
  LPWSTR ptstrName;
} TRUSTEE_W, *PTRUSTEE_W;
typedef enum _ACCESS_MODE {
  NOT_USED_ACCESS = 0,
  GRANT_ACCESS,
  SET_ACCESS,
  DENY_ACCESS,
  REVOKE_ACCESS,
  SET_AUDIT_SUCCESS,
  SET_AUDIT_FAILURE
} ACCESS_MODE;
typedef struct _EXPLICIT_ACCESS_A {
  DWORD grfAccessPermissions;
  ACCESS_MODE grfAccessMode;
  DWORD grfInheritance;
  TRUSTEE_A Trustee;
} EXPLICIT_ACCESS_A, *PEXPLICIT_ACCESS_A;
typedef struct _EXPLICIT_ACCESS_W {
  DWORD grfAccessPermissions;
  ACCESS_MODE grfAccessMode;
  DWORD grfInheritance;
  TRUSTEE_W Trustee;
} EXPLICIT_ACCESS_W, *PEXPLICIT_ACCESS_W;
#define NO_INHERITANCE 0x0
#define SUB_OBJECTS_ONLY_INHERIT 0x1
#define SUB_CONTAINERS_ONLY_INHERIT 0x2
#define SUB_CONTAINERS_AND_OBJECTS_INHERIT 0x3
#define INHERIT_NO_PROPAGATE 0x4
#define INHERIT_ONLY 0x8
#ifdef UNICODE
typedef TRUSTEE_W TRUSTEE, *PTRUSTEE;
typedef EXPLICIT_ACCESS_W EXPLICIT_ACCESS, *PEXPLICIT_ACCESS;
#else
typedef TRUSTEE_A TRUSTEE, *PTRUSTEE;
typedef EXPLICIT_ACCESS_A EXPLICIT_ACCESS, *PEXPLICIT_ACCESS;
#endif

#endif
