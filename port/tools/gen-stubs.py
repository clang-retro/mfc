#!/usr/bin/env python3
# gen-stubs.py - writes port/src/stubs.cpp: a placeholder for each Win32
# function that the layer does not implement yet, so that programs link.
#
#   python3 port/tools/gen-stubs.py
#
# The names are in port/src/stubs.txt, one per line (# starts a comment).
# Each placeholder fails the way the API reports failure: E_NOTIMPL for
# functions returning HRESULT, SQL_ERROR for ODBC, 0 (FALSE, NULL) for the
# rest, and sets ERROR_CALL_NOT_IMPLEMENTED. With WINPORT_DEBUG set in the
# environment, the first call of each prints its name.
#
# Part of clang-retro MFC, an independent implementation of the MFC API.
# SPDX-License-Identifier: AGPL-3.0-only
import os
import re
import sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
names = []
for line in open(os.path.join(root, "src", "stubs.txt")):
    line = line.split("#", 1)[0].strip()
    if line:
        names.append(line)

decls = ""
inc = os.path.join(root, "include")
for f in sorted(os.listdir(inc)):
    decls += open(os.path.join(inc, f)).read()
decls = re.sub(r"\s+", " ", decls)


def return_type(name):
    m = re.search(r"([A-Za-z_][\w \*]*?)\s+(?:WINAPI|WSAAPI|SQL_API|STDAPI|CALLBACK|WINAPIV)?\s*" + name + r"\s*\(",
                  decls)
    if not m:
        sys.exit("gen-stubs: no declaration of " + name)
    t = m.group(1).split()[-1]
    if t in ("HRESULT", "SCODE"):
        return "hresult"
    if t == "SQLRETURN":
        return "sql"
    if t == "void":
        return "void"
    if t in ("double", "float", "DOUBLE", "FLOAT"):
        sys.exit("gen-stubs: floating-point result of " + name)
    return "zero"


out = ["// stubs.cpp - generated by port/tools/gen-stubs.py from stubs.txt; do",
       "// not edit. Placeholders for the functions the layer does not",
       "// implement yet.",
       "//",
       "// Part of clang-retro MFC, an independent implementation of the MFC API.",
       "// SPDX-License-Identifier: AGPL-3.0-only",
       "#include <stdint.h>",
       "",
       "// No headers: each placeholder only needs the right name and a result",
       "// in the return register, whatever its declared arguments.",
       "extern \"C\" void _WinportStub(const char* name, bool* reported);",
       "",
       "#define STUB_ZERO(f)                  \\",
       "  extern \"C\" intptr_t f(void) {      \\",
       "    static bool reported;             \\",
       "    _WinportStub(#f, &reported);      \\",
       "    return 0;                         \\",
       "  }",
       "#define STUB_VOID(f)                  \\",
       "  extern \"C\" void f(void) {          \\",
       "    static bool reported;             \\",
       "    _WinportStub(#f, &reported);      \\",
       "  }",
       "#define STUB_HRESULT(f)               \\",
       "  extern \"C\" int32_t f(void) {       \\",
       "    static bool reported;             \\",
       "    _WinportStub(#f, &reported);      \\",
       "    return (int32_t)0x80004001;       \\",
       "  }",
       "#define STUB_SQL(f)                   \\",
       "  extern \"C\" int16_t f(void) {       \\",
       "    static bool reported;             \\",
       "    _WinportStub(#f, &reported);      \\",
       "    return -1;                        \\",
       "  }",
       ""]
for n in names:
    out.append("STUB_%s(%s)" % (return_type(n).upper(), n))
open(os.path.join(root, "src", "stubs.cpp"), "w").write("\n".join(out) + "\n")
