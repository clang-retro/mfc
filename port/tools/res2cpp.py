#!/usr/bin/env python3
# res2cpp.py - turns a program's resources into C++ for Linux and macOS:
# the compiled .res as a byte array, registered with the portable layer
# when the program starts, so FindResource and the rest find it.
#
#   res2cpp.py [-I dir]... [-D name[=value]]... app.rc -o app-res.cpp
#   res2cpp.py app.res -o app-res.cpp
#
# A .rc file is compiled with llvm-rc ($RC, default llvm-rc). The
# resource compiler understands only the preprocessor, so it does not get
# the portable layer's headers, which are C++: it gets stand-ins for
# them that hold just their macros, which clang ($CXX, default clang++)
# collects with -dM. A .res file is used as it is.
#
# Part of clang-retro MFC, an independent implementation of the MFC API.
# SPDX-License-Identifier: AGPL-3.0-only
import argparse
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
PORT_INCLUDE = os.path.normpath(os.path.join(HERE, "..", "include"))

# A macro the resource compiler can use: an object-like macro whose value
# is numbers, names, strings and operators (no casts or calls).
SIMPLE = re.compile(r'^(?:[\w\s|&^~+\-*/%<>()]|"(?:[^"\\]|\\.)*"|L"(?:[^"\\]|\\.)*")*$')


def rc_headers(outdir, cxx):
    """Writes the stand-in headers into outdir: one per header of the
    portable layer, each including winport-rc.h, which holds the macros."""
    headers = sorted(h for h in os.listdir(PORT_INCLUDE) if h.endswith(".h"))
    src = "".join('#include <%s>\n' % h for h in headers)
    out = subprocess.run([cxx, "-x", "c++", "-std=c++17", "-dM", "-E", "-I", PORT_INCLUDE, "-"],
                         input=src, capture_output=True, text=True)
    if out.returncode != 0:
        sys.stderr.write(out.stderr)
        sys.exit("res2cpp: could not read the portable layer's macros")
    defs = []
    for line in out.stdout.splitlines():
        m = re.match(r"#define (\w+) (.*)$", line)
        if not m or m.group(1).startswith("_"):
            continue
        name, value = m.groups()
        if SIMPLE.match(value):
            defs.append("#define %s %s" % (name, value))
    os.makedirs(outdir, exist_ok=True)
    with open(os.path.join(outdir, "winport-rc.h"), "w") as f:
        f.write("// The portable layer's macros, for the resource compiler.\n#pragma once\n")
        f.write("\n".join(defs) + "\n")
    for h in headers + ["winresrc.h", "winres.h"]:
        with open(os.path.join(outdir, h), "w") as f:
            f.write('#pragma once\n#include "winport-rc.h"\n')


def compile_rc(args, res):
    cxx = os.environ.get("CXX", "clang++")
    rc = os.environ.get("RC", "llvm-rc")
    with tempfile.TemporaryDirectory() as tmp:
        stand_ins = os.path.join(tmp, "include")
        rc_headers(stand_ins, cxx)
        cmd = [rc, "/I", stand_ins]
        for d in args.I:
            cmd += ["/I", d]
        for d in args.D:
            cmd += ["/D", d]
        # Relative names in the script are found from its own directory.
        cmd += ["/I", os.path.dirname(os.path.abspath(args.input)) or "."]
        cmd += ["/FO", res, args.input]
        r = subprocess.run(cmd)
        if r.returncode != 0:
            sys.exit(r.returncode)


def write_cpp(data, path, symbol):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    with open(path, "w") as f:
        f.write("// Generated by res2cpp.py; do not edit.\n")
        f.write("#include <stddef.h>\n\n")
        f.write('extern "C" void _WinportAddResources(const void* anchor, const void* data, size_t size);\n\n')
        f.write("namespace {\n\n")
        f.write("alignas(4) const unsigned char %s[] = {\n" % symbol)
        f.write("\n".join(lines) + "\n};\n\n")
        f.write("struct Register {\n")
        f.write("  Register() { _WinportAddResources(%s, %s, sizeof %s); }\n" % (symbol, symbol, symbol))
        f.write("} registered;\n\n")
        f.write("}  // namespace\n")


def main():
    p = argparse.ArgumentParser(description="Turn resources into C++ for the portable layer.")
    p.add_argument("input", help="a .rc or .res file")
    p.add_argument("-o", dest="output", required=True, help="the .cpp file to write")
    p.add_argument("-I", action="append", default=[], help="an include directory for the .rc file")
    p.add_argument("-D", action="append", default=[], help="a macro for the .rc file")
    args = p.parse_args()
    if args.input.lower().endswith(".res"):
        data = open(args.input, "rb").read()
    else:
        with tempfile.TemporaryDirectory() as tmp:
            res = os.path.join(tmp, "out.res")
            compile_rc(args, res)
            data = open(res, "rb").read()
    write_cpp(data, args.output, "kResources")


if __name__ == "__main__":
    main()
