#!/usr/bin/env python3
"""Generate include/afxres.rc, include/afxprint.rc, include/afxolecl.rc and
include/afxolesv.rc.

Programs written for MFC include these from their own resource scripts
(AppWizard puts `#include "afxres.rc"` and `#include "afxprint.rc"` in
every .rc file). The strings come from the library's built-in table in
src/state.cpp, so the two always agree; strings a program defines itself
(the idle message, the indicators, the command prompts) are left out, as
a second definition of a string is an error.
"""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def strings():
    src = open(os.path.join(ROOT, 'src', 'state.cpp')).read()
    table = src[src.index('g_defaultStrings[] = {'):]
    table = table[:table.index('\n};')]
    for m in re.finditer(r'\{(\w+),\s*((?:"(?:[^"\\]|\\.)*"\s*)+)\}', table):
        text = ''.join(re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(2)))
        yield m.group(1), text

def rc_string(text):
    # C escapes to resource-script ones: \n stays, quotes double.
    return '"' + text.replace('\\"', '""') + '"'

PROGRAM_STRINGS = ('AFX_IDS_IDLEMESSAGE', 'AFX_IDS_HELPMODEMESSAGE', 'AFX_IDS_PREVIEW_CLOSE')
OLE_CONTAINER_STRINGS = ('AFX_IDP_STATIC_OBJECT', 'AFX_IDP_FAILED_TO_CONNECT',
                         'AFX_IDP_SERVER_BUSY', 'AFX_IDP_BAD_VERB', 'AFX_IDP_FAILED_TO_NOTIFY',
                         'AFX_IDP_FAILED_TO_LAUNCH', 'AFX_IDP_ASK_TO_UPDATE',
                         'AFX_IDP_FAILED_TO_UPDATE', 'AFX_IDP_FAILED_TO_CONVERT',
                         'AFX_IDP_FAILED_TO_CREATE', 'AFX_IDS_UNKNOWNTYPE',
                         'AFX_IDS_EMBED_FORMAT', 'AFX_IDS_LINKSOURCE_FORMAT',
                         'AFX_IDS_METAFILE_FORMAT', 'AFX_IDS_DIB_FORMAT', 'AFX_IDS_BITMAP_FORMAT',
                         'AFX_IDS_UPDATING_ITEMS', 'AFX_IDS_RTF_FORMAT_TEXT')
OLE_SERVER_STRINGS = ('AFX_IDS_UPDATE_MENU', 'AFX_IDS_EXIT_MENU')
PRINT_PREFIXES = ('AFX_IDS_PRINT', 'AFX_IDS_ONEPAGE', 'AFX_IDS_TWOPAGE', 'AFX_IDS_PREVIEWPAGEDESC')

def main():
    res, prn, ole, svr = [], [], [], []
    for name, text in strings():
        if name in PROGRAM_STRINGS or name.startswith(('ID_', 'AFX_ID_PREVIEW', 'AFX_IDS_SC')):
            continue
        if name == 'AFX_IDS_MDICHILD':
            continue
        if name in OLE_CONTAINER_STRINGS:
            ole.append((name, text))
            continue
        if name in OLE_SERVER_STRINGS:
            svr.append((name, text))
            continue
        (prn if name.startswith(PRINT_PREFIXES) else res).append((name, text))

    head = ('// {0} - generated by tools/gen-rc.py; do not edit.\n'
            '//\n// {1}\n//\n'
            '// Part of clang-retro MFC, an independent implementation of the MFC API.\n'
            '// SPDX-License-Identifier: AGPL-3.0-only\n\n'
            '#include <afxres.h>\n\n')

    with open(os.path.join(ROOT, 'include', 'afxres.rc'), 'w') as f:
        f.write(head.format('afxres.rc', 'The framework\'s messages, for programs that include it\n'
                            '// from their resource script. Without it, the library uses the\n'
                            '// same built-in text.'))
        f.write('STRINGTABLE\nBEGIN\n')
        for name, text in res:
            f.write('  {0} {1}\n'.format(name, rc_string(text)))
        f.write('END\n')

    with open(os.path.join(ROOT, 'include', 'afxprint.rc'), 'w') as f:
        f.write(head.format('afxprint.rc', 'The printing dialog, the print preview toolbar and their\n'
                            '// strings. Without it, the library builds the same dialogs in memory.'))
        f.write('''AFX_IDD_PRINTDLG DIALOG 0, 0, 133, 64
STYLE DS_MODALFRAME | DS_CENTER | WS_POPUP | WS_CAPTION | WS_SYSMENU
CAPTION "Printing"
FONT 8, "MS Shell Dlg"
BEGIN
  CTEXT "", AFX_IDC_PRINT_DOCNAME, 0, 8, 133, 8
  CTEXT "", AFX_IDC_PRINT_PRINTERNAME, 0, 18, 133, 8
  CTEXT "", AFX_IDC_PRINT_PAGENUM, 0, 28, 133, 8
  DEFPUSHBUTTON "Cancel", IDCANCEL, 44, 42, 45, 15
END

AFX_IDD_PREVIEW_TOOLBAR DIALOG 0, 0, 333, 16
STYLE WS_CHILD
FONT 8, "MS Shell Dlg"
BEGIN
  PUSHBUTTON "&Print...", AFX_ID_PREVIEW_PRINT, 4, 2, 44, 12
  PUSHBUTTON "&Next Page", AFX_ID_PREVIEW_NEXT, 51, 2, 44, 12
  PUSHBUTTON "Pre&v Page", AFX_ID_PREVIEW_PREV, 98, 2, 44, 12
  PUSHBUTTON "&Two Page", AFX_ID_PREVIEW_NUMPAGE, 145, 2, 44, 12
  PUSHBUTTON "Zoom &In", AFX_ID_PREVIEW_ZOOMIN, 192, 2, 44, 12
  PUSHBUTTON "Zoom &Out", AFX_ID_PREVIEW_ZOOMOUT, 239, 2, 44, 12
  PUSHBUTTON "&Close", AFX_ID_PREVIEW_CLOSE, 286, 2, 44, 12
END

''')
        f.write('STRINGTABLE\nBEGIN\n')
        for name, text in prn:
            f.write('  {0} {1}\n'.format(name, rc_string(text)))
        f.write('END\n')

    with open(os.path.join(ROOT, 'include', 'afxolecl.rc'), 'w') as f:
        f.write(head.format('afxolecl.rc', 'The OLE container messages. Without it, the library uses\n'
                            '// the same built-in text.'))
        f.write('STRINGTABLE\nBEGIN\n')
        for name, text in ole:
            f.write('  {0} {1}\n'.format(name, rc_string(text)))
        f.write('END\n')

    with open(os.path.join(ROOT, 'include', 'afxolesv.rc'), 'w') as f:
        f.write(head.format('afxolesv.rc', 'The OLE server menu text. Without it, the library uses the\n'
                            '// same built-in text.'))
        f.write('STRINGTABLE\nBEGIN\n')
        for name, text in svr:
            f.write('  {0} {1}\n'.format(name, rc_string(text)))
        f.write('END\n')

main()
